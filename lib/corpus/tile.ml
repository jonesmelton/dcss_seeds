(* Every parchment shares one [sub_type] shape and differs only in the spell
   named in it, so the art is picked by that spell's tier. Crawl draws these by
   spell *school* over three tiers; we draw three tiers and no school, because at
   the size this page sets a tile, school is a few pixels of tint. *)
let of_item ~base_type ~sub_type ~artefact =
  let key = base_type, sub_type in
  match if artefact then Map.find randart_tiles key else None with
  | Some _ as t -> t
  | None ->
    (match Map.find base_tiles key with
     | Some _ as t -> t
     | None ->
       if String.equal base_type "book"
       then
         Option.map (Spell.of_parchment sub_type) ~f:(fun tier ->
           sprintf "items/parchment_%s.png" (Spell.Tier.to_string tier))
       else None)
;;

let known_items = Map.keys base_tiles

let of_entry (e : Record.Entry.t) =
  match e.feat with
  | Some feat -> of_feat feat
  | None ->
    (match e.unique_mons, e.base_type, e.sub_type with
     | Some true, _, _ -> of_unique e.name
     | _, Some base_type, Some sub_type ->
       of_item ~base_type ~sub_type ~artefact:(Option.value e.artefact ~default:false)
     | _ -> None)
;;
