(* Keyed by the pair the corpus stores, not by a name: [name] carries
   enchantment and brand, so it identifies one item rather than a type. Crawl's
   own item enums and tile enums have drifted apart over renames -- an item's
   [TALISMAN_SERPENT] is a tile's [TALISMAN_SNAKE], and [WPN_SLING] names the
   sling in one table and its ammunition in another -- so this is generated by
   joining the two through crawl's source. *)
module Key = struct
  module T = struct
    type t = string * string [@@deriving compare, sexp_of]
  end

  include T
  include Comparator.Make (T)
end

